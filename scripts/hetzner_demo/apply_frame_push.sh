#!/usr/bin/env bash
# ============================================================================
# apply_frame_push.sh — expose a frame's ntfy sidecar publicly so Pocket phone
# pairing works, mirroring push.theprotocol.cloud exactly.
#
# Strategy + rationale: PRODUCTION_DOCS/08_SECURITY/Frame_Outbound_Mail_And_Push.md
#
# WHAT IS ALREADY TRUE WITHOUT THIS SCRIPT
#   The ntfy sidecar runs and the registry publishes to it over the internal
#   docker network, and W3C Web Push (VAPID, browser) works fully — the VAPID
#   keypair is generated into the frame's OWN registry_signing_keys (mig 0133) and
#   delivery goes to the browser vendor. This script only adds the PHONE-app
#   pairing path, which needs a public hostname.
#
# THE ONE PROPERTY THAT MUST NOT BE LOST
#   The public vhost limits methods to GET, which alone is NOT subscribe-only: ntfy also publishes on GET
#   (/<topic>/publish?message=, /send, /trigger; measured 2026-09-15). A §MTLSHOPS frame's edge door is a path
#   allowlist, and step 5 refuses a door that lets any GET publish form through.
#   Publishing stays internal. If publish were reachable publicly, anyone who
#   learned a topic name could push arbitrary notifications to a paired phone.
#
# Prereq (ours, never the frame operator's — PART 11b):
#   DNS A record <host> -> this box, e.g.
#     push.hetzner.theprotocol.cloud A <this host's public IP>
#
# Usage:
#   ./apply_frame_push.sh --host push.hetzner.theprotocol.cloud --ntfy-port 8099 \
#       [--stack /opt/theprotocol/stack/hetzner-frame-1785128860] \
#       [--service hetzner-frame-registry] [--ntfy-container hetzner-frame-ntfy] \
#       [--dry-run]
# ============================================================================
set -euo pipefail

HOST=""; NTFY_PORT=""; DRY=0
STACK="/opt/theprotocol/stack/hetzner-frame-1785128860"
SERVICE="hetzner-frame-registry"; NTFY_C="hetzner-frame-ntfy"
COMPOSE="docker-compose.frame-test.yml"
LOAD_MAX=60

while [ $# -gt 0 ]; do
  case "$1" in
    --host) HOST="$2"; shift 2;;
    --ntfy-port) NTFY_PORT="$2"; shift 2;;
    --stack) STACK="$2"; shift 2;;
    --service) SERVICE="$2"; shift 2;;
    --ntfy-container) NTFY_C="$2"; shift 2;;
    --dry-run) DRY=1; shift;;
    *) echo "unknown arg: $1" >&2; exit 2;;
  esac
done
[ -n "$HOST" ] || { echo "FATAL: --host required" >&2; exit 2; }
[ -n "$NTFY_PORT" ] || { echo "FATAL: --ntfy-port required" >&2; exit 2; }

# ── 1. DNS must exist first, or certbot will fail and leave a broken vhost ──
IP=$(dig +short "$HOST" A | tail -1)
MYIP=$(curl -s --max-time 10 https://api.ipify.org || echo "")
if [ -z "$IP" ]; then
  echo "ABORT: $HOST does not resolve. Create the A record first:" >&2
  echo "       $HOST A ${MYIP:-<this box>}" >&2
  exit 1
fi
echo "[dns] $HOST -> $IP"
[ -n "$MYIP" ] && [ "$IP" != "$MYIP" ] && echo "[dns] WARNING: resolves to $IP but this box is $MYIP"

LOAD1=$(awk '{print int($1)}' /proc/loadavg)
[ "$LOAD1" -lt "$LOAD_MAX" ] || { echo "ABORT: load1m=$LOAD1 >= $LOAD_MAX (PART 1)" >&2; exit 1; }
echo "[gate] load1m=$LOAD1 OK"

VHOST="/etc/nginx/sites-available/${HOST%%.*}-$(echo "$HOST" | cut -d. -f2)"
VHOST="/etc/nginx/sites-available/push-$(echo "$HOST" | cut -d. -f2)"
LINK="/etc/nginx/sites-enabled/$(basename "$VHOST")"

# ── 2. Certificate (HTTP-01, per-name — a single-label wildcard will NOT cover
#       a 4th-level name like push.hetzner.theprotocol.cloud) ───────────────
if [ ! -d "/etc/letsencrypt/live/$HOST" ]; then
  echo "[cert] issuing for $HOST"
  [ "$DRY" -eq 1 ] || certbot certonly --nginx -d "$HOST" --non-interactive --agree-tos \
      --register-unsafely-without-email --keep-until-expiring
else
  echo "[cert] already present for $HOST"
fi

# ── 3. vhost, copied from the frame-a precedent ────────────────────────────
echo "[nginx] writing $VHOST"
if [ "$DRY" -eq 0 ]; then
cat > "$VHOST" <<EOF
# TheProtocol Pocket Push — ntfy public endpoint for a FRAME
# $HOST -> 127.0.0.1:$NTFY_PORT ($NTFY_C)
# Public side is SUBSCRIBE-ONLY (read). Publishing stays internal-only
# (registry -> http://$NTFY_C over the docker network).
# Generated by scripts/hetzner_demo/apply_frame_push.sh on $(date -Is)
# Doc: PRODUCTION_DOCS/08_SECURITY/Frame_Outbound_Mail_And_Push.md

server {
    listen 80;
    server_name $HOST;
    location /.well-known/acme-challenge/ { root /var/www/html; default_type text/plain; }
    location / { return 301 https://\$host\$request_uri; }
}

server {
    listen 443 ssl http2;
    server_name $HOST;

    ssl_certificate     /etc/letsencrypt/live/$HOST/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$HOST/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_prefer_server_ciphers off;

    add_header Strict-Transport-Security "max-age=63072000" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;

    # §PUSH (2026-10-06): subscribe only, by PATH. limit_except GET alone let ntfy's GET publish forms through
    # (/publish, /send, /trigger; since v2.16 also GET delete/read/clear), which step 5 below refuses: the same
    # allowlist the frame template's push vhost and the live EU/ASIA vhosts carry.
    location = /v1/health {
        limit_except GET { deny all; }
        proxy_pass http://127.0.0.1:$NTFY_PORT;
        proxy_set_header Host              \$host;
        proxy_set_header X-Real-IP         \$remote_addr;
        proxy_set_header X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }

    location ~ "^/[-_A-Za-z0-9]{1,64}(,[-_A-Za-z0-9]{1,64})*/(json|sse|raw|ws|auth)\$" {
        limit_except GET { deny all; }
        proxy_pass http://127.0.0.1:$NTFY_PORT;
        proxy_http_version 1.1;
        proxy_set_header Host              \$host;
        proxy_set_header X-Real-IP         \$remote_addr;
        proxy_set_header X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header Upgrade           \$http_upgrade;
        proxy_set_header Connection        "upgrade";
        proxy_buffering off;
        proxy_read_timeout 350s;
        proxy_send_timeout 350s;
    }

    location / {
        return 403;
    }
}
EOF
ln -sf "$VHOST" "$LINK"
nginx -t || { echo "FATAL: nginx config test failed; removing link" >&2; rm -f "$LINK"; nginx -t; exit 1; }
systemctl reload nginx
echo "[nginx] reloaded"
fi

# ── 4. Tell the frame + ntfy their public identity ────────────────────────
cd "$STACK"
STAMP=$(date +%Y%m%d-%H%M%S)
cp -p "$COMPOSE" "$COMPOSE.bak-pre-pushpublic-$STAMP"
if [ "$DRY" -eq 0 ]; then
python3 - "$COMPOSE" "$HOST" "$NTFY_C" <<'PY'
import sys, re
p, host, ntfy = sys.argv[1], sys.argv[2], sys.argv[3]
s = open(p).read()
# Presence must be tested on a real YAML KEY, not a substring: both names also
# appear in explanatory COMMENTS in this file, so a plain `in s` test matched the
# comment, took the else-branch, regex-matched nothing and silently changed
# nothing while still printing success. (Found live 2026-08-01.)
has_pub = re.search(r'^\s*PUSH_NTFY_PUBLIC_URL:', s, re.M)
if not has_pub:
    s, n = re.subn(r'(\n(\s+)PUSH_NTFY_URL: [^\n]+)',
                   rf'\1\n\2PUSH_NTFY_PUBLIC_URL: https://{host}', s, count=1)
    assert n == 1, "could not anchor on PUSH_NTFY_URL"
else:
    s, n = re.subn(r'^(\s*)PUSH_NTFY_PUBLIC_URL:.*$', rf'\g<1>PUSH_NTFY_PUBLIC_URL: https://{host}', s, flags=re.M)
    assert n >= 1, "PUSH_NTFY_PUBLIC_URL key present but not replaced"
if not re.search(r'^\s*NTFY_BASE_URL:', s, re.M):
    s, n = re.subn(rf'(\n(\s+)NTFY_CACHE_FILE: [^\n]+)',
                   rf'\1\n\2NTFY_BASE_URL: https://{host}', s, count=1)
    assert n == 1, "could not anchor on NTFY_CACHE_FILE"
open(p, "w").write(s)
out = open(p).read() if False else s
assert re.search(r'^\s*PUSH_NTFY_PUBLIC_URL: https://' + re.escape(host), out, re.M), \
    "PUSH_NTFY_PUBLIC_URL not present after edit"
assert re.search(r'^\s*NTFY_BASE_URL: https://' + re.escape(host), out, re.M), \
    "NTFY_BASE_URL not present after edit"
print(f"[compose] PUSH_NTFY_PUBLIC_URL + NTFY_BASE_URL -> https://{host} (asserted present)")
PY
docker compose -f "$COMPOSE" --env-file .env.frame-test config >/dev/null || {
    echo "FATAL: compose invalid; restoring" >&2; cp -p "$COMPOSE.bak-pre-pushpublic-$STAMP" "$COMPOSE"; exit 1; }
docker compose -f "$COMPOSE" --env-file .env.frame-test up -d --no-deps --force-recreate "$NTFY_C" "$SERVICE" >/dev/null
echo "[deploy] $NTFY_C + $SERVICE recreated"
fi

# ── 5. Prove it: subscribe must work, publish must be refused ─────────────
if [ "$DRY" -eq 0 ]; then
  sleep 5
  SUB=$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 "https://$HOST/v1/health")
  PUB=$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 -X POST -d hi "https://$HOST/probe-topic")
  echo "[verify] GET /v1/health = $SUB (want 200)   POST publish = $PUB (want 403)"
  [ "$SUB" = "200" ] || { echo "FAIL: public subscribe is not working" >&2; exit 1; }
  [ "$PUB" = "403" ] || { echo "FAIL: public PUBLISH was not refused — this is the dangerous one" >&2; exit 1; }
  # §MTLSHOPS (2026-09-15): ntfy publishes on GET too, so each GET form must be refused, and a subscribe stream must answer
  SUBT=$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 "https://$HOST/probe-topic/json?poll=1")
  GETPUB=""
  for f in "probe-topic/publish?message=hi" "probe-topic/send?message=hi" "probe-topic/trigger"; do
    GETPUB="$GETPUB $(curl -s -o /dev/null -w '%{http_code}' --max-time 10 "https://$HOST/$f")"
  done
  echo "[verify] GET /probe-topic/json?poll=1 = $SUBT (want 200)   GET publish forms =$GETPUB (want 403 403 403)"
  [ "$SUBT" = "200" ] || { echo "FAIL: a public subscribe stream is not served" >&2; exit 1; }
  [ "$GETPUB" = " 403 403 403" ] || { echo "FAIL: a public GET publish form was not refused" >&2; exit 1; }
  echo "[verify] subscribe-only confirmed"
fi
echo "DONE. Rollback: rm $LINK && systemctl reload nginx; cp -p $COMPOSE.bak-pre-pushpublic-$STAMP $COMPOSE && recreate."
