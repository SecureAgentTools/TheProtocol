def bare_name(tool_name: str) -> str:
    """Wire names carry the theprotocol_ prefix; the maps store bare names."""
    return tool_name[12:] if tool_name.startswith("theprotocol_") else tool_name


def get_category(tool_name: str, *, is_admin: bool = False) -> str:
    """Category for a tool (accepts wire or bare name). Unknown → misc."""
    table = ADMIN_TOOL_CATEGORIES if is_admin else PUBLIC_TOOL_CATEGORIES
    cat = table.get(bare_name(tool_name))
    if cat is None:
        logger.warning("mcp.tool_categories: no category for %r (is_admin=%s) — "
                       "add it to the map (4th wiring place); listing as 'misc'", tool_name, is_admin)
        return "misc"
    return cat


def parse_toolsets(raw: Optional[str], *, is_admin: bool = False) -> Tuple[Optional[Set[str]], List[str]]:
    """Parse a comma-separated toolsets string. Returns (selected|None, unknown_names).

    None = no filtering requested (full list). "core" is always implicitly included
    when any filtering is active so the daily drivers stay reachable.
    """
    if raw is None or not raw.strip():
        return None, []
    buckets = ADMIN_BUCKETS if is_admin else PUBLIC_BUCKETS
    known = set(buckets)
    if not is_admin:
        known |= set(PUBLIC_OVERLAY_BUCKETS)  # overlays are selectable names too
    requested = {p.strip() for p in raw.split(",") if p.strip()}
    unknown = sorted(n for n in requested if n not in known)
    selected = {n for n in requested if n in known}
    selected.add("core")
    return selected, unknown


def filter_schemas(schemas: Iterable[dict], toolsets: Optional[Set[str]], *, is_admin: bool = False) -> List[dict]:
    """Filter tool schema dicts by bucket selection. toolsets=None → unchanged list.

    A schema passes if its PRIMARY category is selected, OR (public only) its
    bare name is a member of any selected OVERLAY bucket — overlays are
    additive cross-cuts, they never remove a tool from its primary bucket.
    """
    if toolsets is None:
        return list(schemas)
    overlay_members: Set[str] = set()
    if not is_admin:
        for name in toolsets:
            entry = PUBLIC_OVERLAY_BUCKETS.get(name)
            if entry:
                overlay_members |= entry[1]
    return [
        s for s in schemas
        if get_category(s.get("name", ""), is_admin=is_admin) in toolsets
        or (overlay_members and bare_name(s.get("name", "")) in overlay_members)
    ]


