"""Funding Request End-to-End Flow.

Tests the full funding workflow: agent request → admin approval → auto-fund
from treasury → balance increase → events emitted.

Catches:
  • State machine bugs (PENDING → APPROVED → FUNDED transitions)
  • Missing event emission (FundingRequestApproved, TokensTransferred from treasury)
  • Admin authorization gaps on /admin/funding/{id}/approve
  • Auto-fund failures (request approved but balance not credited)

Sandbox-only.
"""
from __future__ import annotations

import asyncio
import logging
import time
from datetime import datetime, timezone
from typing import Any, Dict

from agentvault_registry.api_tests.base import APITestBase
from agentvault_registry.api_tests.multiframe_helpers import (
    SANDBOX_TARGET, get_target,
    login_admin, onboard_agent, get_agent_jwt,
    query_event_count, http_in_container, teg_balance_for,
)

logger = logging.getLogger(__name__)


class TestFlowFundingRequest(APITestBase):
    CATEGORY_NAME = "flow_funding_request"
    flow_values: Dict[str, Any] = {}

    async def setup(self):
        await self.setup_category(self.CATEGORY_NAME)
        self.flow_values = {}

    async def teardown(self):
        return

    async def test_all(self, developer_token=None, agent_token=None):
        std = await self.test_category_endpoints(
            category=self.CATEGORY_NAME,
            developer_token=developer_token,
            agent_token=agent_token,
            priority_only=False,
        )
        std["flow_tests"] = await self.test_funding_flow(developer_token)
        return std

    async def test_funding_flow(self, developer_token: str) -> Dict[str, Any]:
        logger.info("=" * 60)
        logger.info("Starting Funding Request End-to-End Flow")
        logger.info("=" * 60)

        target = get_target("sandbox")
        results = []
        ts = int(time.time()) % 100000
        REQUEST_AMOUNT = 1000.0

        # Step 0: admin login
        ok_a, dev_jwt, det = await login_admin(target, "a")
        if not ok_a:
            results.append(self._fail_step(1, "Admin login", det))
            return self._summarize(results, False)

        # Snapshot baseline
        baseline_approved = max(0, query_event_count(target.a_es_db_container, "FundingRequestApproved"))
        baseline_tt = max(0, query_event_count(target.a_es_db_container, "TokensTransferred"))

        # Step 1: onboard agent
        ok, agent_info, det = await onboard_agent(target, "a", dev_jwt, f"funding-test-{ts}")
        results.append({
            "step": 1, "name": f"Onboard funding-test-{ts}",
            "path": "/onboard/create_agent", "method": "POST", "authRequired": "none",
            "healthy": ok, "statusCode": 200 if ok else 500,
            "responseData": {"did": (agent_info or {}).get("did", "")[:30] + "..." if ok else None,
                             "detail": det},
            "error": None if ok else det,
            "timestamp": datetime.now(timezone.utc).isoformat(),
        })
        if not ok:
            return self._summarize(results, False)

        # Step 2: get agent JWT
        ok_jwt, agent_jwt, det = await get_agent_jwt(target, "a", agent_info["client_id"], agent_info["client_secret"])
        if not ok_jwt:
            results.append(self._fail_step(2, "Get agent JWT", det))
            return self._summarize(results, False)

        # Step 3: snapshot pre-funding TEG balance
        balance_pre = await teg_balance_for(target, "a", agent_info["did"], dev_jwt)
        balance_pre_known = balance_pre is not None
        results.append({
            "step": 2, "name": "Snapshot pre-funding TEG balance",
            "path": "/admin/agents/{agent_id}/balance", "method": "GET", "authRequired": "developer",
            "healthy": balance_pre_known, "statusCode": 200 if balance_pre_known else 500,
            "responseData": {"balance": balance_pre},
            "error": None if balance_pre_known else "TEG balance unreadable",
            "timestamp": datetime.now(timezone.utc).isoformat(),
        })

        # Step 4: as agent, POST /funding/request
        ok, body, code = await http_in_container(
            target.a_registry_container, "POST", "/api/v1/funding/request",
            body={
                "amount": str(REQUEST_AMOUNT),
                "reason": f"API tester funding flow {ts} — auto-generated by flow_funding_request_complete",
            },
            jwt=agent_jwt, timeout=15,
        )
        request_id = None
        if ok and isinstance(body, dict):
            request_id = body.get("id") or body.get("request_id")
        results.append({
            "step": 3, "name": "Agent submits funding request",
            "path": "/funding/request", "method": "POST", "authRequired": "agent",
            "healthy": ok and bool(request_id),
            "statusCode": int(code) if code.isdigit() else 500,
            "responseData": {"request_id": request_id, "amount": str(REQUEST_AMOUNT),
                             "raw": str(body)[:120]},
            "error": None if (ok and request_id) else f"http={code}",
            "timestamp": datetime.now(timezone.utc).isoformat(),
        })
        if not (ok and request_id):
            return self._summarize(results, False)

        # Step 5: admin lists pending — verify our request is there
        ok, body, code = await http_in_container(
            target.a_registry_container, "GET", "/api/v1/admin/funding/pending",
            jwt=dev_jwt, timeout=15,
        )
        pending_list = []
        if ok and isinstance(body, dict):
            pending_list = body.get("requests") or body.get("items") or []
        elif isinstance(body, list):
            pending_list = body
        in_pending = any(
            isinstance(r, dict) and str(r.get("id")) == str(request_id)
            for r in pending_list
        ) if isinstance(pending_list, list) else False
        results.append({
            "step": 4, "name": "Admin GET /admin/funding/pending — request listed",
            "path": "/admin/funding/pending", "method": "GET", "authRequired": "developer",
            "healthy": ok and in_pending,
            "statusCode": int(code) if code.isdigit() else 500,
            "responseData": {
                "request_id": request_id,
                "in_pending_list": in_pending,
                "pending_count": len(pending_list) if isinstance(pending_list, list) else 0,
            },
            "error": None if (ok and in_pending) else f"request not in pending list (http={code})",
            "timestamp": datetime.now(timezone.utc).isoformat(),
        })

        # Step 6: admin approves
        ok, body, code = await http_in_container(
            target.a_registry_container, "POST",
            f"/api/v1/admin/funding/{request_id}/approve",
            body={"approved_amount": str(REQUEST_AMOUNT)},
            jwt=dev_jwt, timeout=30,
        )
        approve_status = body.get("status") if (ok and isinstance(body, dict)) else None
        results.append({
            "step": 5, "name": "Admin approves funding request",
            "path": "/admin/funding/{request_id}/approve", "method": "POST", "authRequired": "developer",
            "healthy": ok and approve_status in ("FUNDED", "APPROVED", "funded", "approved"),
            "statusCode": int(code) if code.isdigit() else 500,
            "responseData": {"approve_status": approve_status, "raw": str(body)[:200]},
            "error": None if (ok and approve_status) else f"http={code}",
            "timestamp": datetime.now(timezone.utc).isoformat(),
        })

        # Step 7: settle 3s, verify post-funding balance
        await asyncio.sleep(3)
        balance_post = await teg_balance_for(target, "a", agent_info["did"], dev_jwt)
        delta = (balance_post - (balance_pre or 0.0)) if balance_post is not None else 0.0
        balance_correct = (
            balance_post is not None
            and abs(delta - REQUEST_AMOUNT) < 0.01
        )
        results.append({
            "step": 6, "name": f"Post-funding TEG balance delta == {REQUEST_AMOUNT}",
            "path": "/admin/agents/{agent_id}/balance", "method": "GET", "authRequired": "developer",
            "healthy": balance_correct,
            "statusCode": 200 if balance_correct else 500,
            "responseData": {
                "balance_pre": balance_pre,
                "balance_post": balance_post,
                "delta": delta,
                "expected_delta": REQUEST_AMOUNT,
            },
            "error": None if balance_correct else f"balance delta wrong: got {delta}, expected {REQUEST_AMOUNT}",
            "timestamp": datetime.now(timezone.utc).isoformat(),
        })

        # Step 8: verify FundingRequestApproved event emitted on EventStore
        post_approved = max(0, query_event_count(target.a_es_db_container, "FundingRequestApproved"))
        post_tt = max(0, query_event_count(target.a_es_db_container, "TokensTransferred"))
        delta_approved = post_approved - baseline_approved
        delta_tt = post_tt - baseline_tt
        events_correct = delta_approved >= 1 and delta_tt >= 1
        results.append({
            "step": 7, "name": "EventStore: FundingRequestApproved + TokensTransferred emitted",
            "path": "/admin/eventstore-stats", "method": "GET", "authRequired": "developer",
            "healthy": events_correct,
            "statusCode": 200,
            "responseData": {
                "delta_FundingRequestApproved": delta_approved,
                "delta_TokensTransferred": delta_tt,
                "expected_min_each": 1,
            },
            "error": None if events_correct else (
                f"event emission gap: FRA={delta_approved} TT={delta_tt} (both should be ≥1)"
            ),
            "timestamp": datetime.now(timezone.utc).isoformat(),
        })

        # Step 9: agent's /funding/my-requests shows status=FUNDED
        ok, body, code = await http_in_container(
            target.a_registry_container, "GET", "/api/v1/funding/my-requests",
            jwt=agent_jwt, timeout=15,
        )
        my_requests = []
        if ok and isinstance(body, dict):
            my_requests = body.get("requests") or body.get("items") or []
        elif isinstance(body, list):
            my_requests = body
        ours_funded = any(
            isinstance(r, dict)
            and str(r.get("id")) == str(request_id)
            and r.get("status", "").upper() in ("FUNDED", "APPROVED")
            for r in my_requests
        ) if isinstance(my_requests, list) else False
        results.append({
            "step": 8, "name": "Agent GET /funding/my-requests — request marked FUNDED",
            "path": "/funding/my-requests", "method": "GET", "authRequired": "agent",
            "healthy": ok and ours_funded,
            "statusCode": int(code) if code.isdigit() else 500,
            "responseData": {
                "request_id": request_id,
                "found_funded": ours_funded,
                "my_request_count": len(my_requests) if isinstance(my_requests, list) else 0,
            },
            "error": None if (ok and ours_funded) else f"request not in FUNDED state",
            "timestamp": datetime.now(timezone.utc).isoformat(),
        })

        self.flow_values = {
            "agent_did": agent_info["did"],
            "request_id": request_id,
            "amount_requested": REQUEST_AMOUNT,
            "balance_pre": balance_pre,
            "balance_post": balance_post,
            "delta_balance": delta,
            "delta_FundingRequestApproved": delta_approved,
            "delta_TokensTransferred": delta_tt,
        }
        return self._summarize(results, True)

    def _fail_step(self, step, name, detail):
        return {
            "step": step, "name": name, "path": "/auth/login", "method": "POST",
            "healthy": False, "statusCode": 500,
            "responseData": {"detail": detail}, "error": detail,
            "timestamp": datetime.now(timezone.utc).isoformat(),
        }

    def _summarize(self, results, flow_success: bool) -> Dict[str, Any]:
        total = len(results)
        ok = sum(1 for r in results if r.get("healthy"))
        return {
            "flow_name": "flow_funding_request_complete",
            "success": flow_success and ok == total,
            "total_steps": total,
            "successful_steps": ok,
            "results": results,
            "flow_values": dict(self.flow_values),
        }
